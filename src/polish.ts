/**
 * Механическая правка перевода.
 *
 * Часть огрехов — не про качество перевода, а про типографику: в английских и
 * корейских веб-новеллах многоточие ставят шестью точками, а то и десятью, и
 * модель послушно переносит это в русский текст. Просить её об этом в промпте
 * можно, но проверять нечем и стоит это токенов на каждой главе; здесь то же
 * самое делается даром и одинаково.
 *
 * Правила тут только те, в которых нельзя ошибиться. Всё, что зависит от
 * смысла, — дело промпта, а не замены по образцу.
 */

export function polish(text: string): string {
  return (
    text
      // Многоточие: сколько бы точек ни стояло, по-русски их три.
      .replace(/\.{4,}/g, "...")
      // Дефис или короткое тире в начале реплики — это тире.
      .replace(/^[-–]\s+/gm, "— ")
      // Пробел перед знаком препинания — след переноса, а не решение автора.
      .replace(/[ \t]+([,.;:!?…])/g, "$1")
      // Больше одного пробела подряд внутри строки.
      .replace(/([^\n]) {2,}/g, "$1 ")
      // Больше одной пустой строки подряд между абзацами.
      .replace(/\n{3,}/g, "\n\n")
      .trim()
  );
}
